// Builds src/exercises/library.ts and src/exercises/tips.ts from free-exercise-db
// (github.com/yuhonas/free-exercise-db, public domain under the Unlicense).
//   curl -sLo /tmp/exercises.json https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json
//   npm --workspace @rei/shared run build:exercises -- /tmp/exercises.json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('Pass the path to exercises.json (see the comment at the top).');
const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/exercises');
const all = JSON.parse(readFileSync(src, 'utf8')).sort((a, b) => a.name.localeCompare(b.name));

const CATEGORY = { strength: 's', powerlifting: 'p', 'olympic weightlifting': 'o', strongman: 'm', plyometrics: 'y', cardio: 'c', stretching: 't' };
const rows = all.map(x => [
  x.id,
  x.name.trim(),
  CATEGORY[x.category] ?? 's',
  x.equipment ?? 'other',
  x.level ?? 'beginner',
  x.mechanic ?? '',
  x.primaryMuscles.join(','),
  x.secondaryMuscles.join(','),
  x.images?.length ?? 0,
]);

// Form tips: the steps, without the generic "repeat for the recommended reps" line.
const tips = Object.fromEntries(
  all.map(x => [x.id, x.instructions.filter(s => !/^repeat\b/i.test(s.trim())).map(s => s.trim()).filter(Boolean).slice(0, 6)]),
);

const header = `// Generated by scripts/build-exercises.mjs from free-exercise-db
// (github.com/yuhonas/free-exercise-db, public domain under the Unlicense). Do not edit.`;
const lines = rows => JSON.stringify(rows).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]');
writeFileSync(
  join(dir, 'library.ts'),
  `${header}
// [id, name, category, equipment, level, mechanic, primary muscles, secondary muscles, image count].
// Categories: s strength, p powerlifting, o olympic, m strongman, y plyometrics, c cardio, t stretching.
export const LIBRARY: [string, string, string, string, string, string, string, string, number][] = ${lines(rows)};
`,
);
writeFileSync(
  join(dir, 'tips.ts'),
  `${header}
// Step-by-step form cues per exercise id. Only the app imports this (it's large).
export const TIPS: Record<string, string[]> = ${JSON.stringify(tips, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{"/, '{\n  "').replace(/\]\}$/, '],\n}')};
`,
);
console.log(`Wrote ${rows.length} exercises to ${dir}`);
